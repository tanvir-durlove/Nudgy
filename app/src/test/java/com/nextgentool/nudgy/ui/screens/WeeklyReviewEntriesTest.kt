/**
 * Sprint 4-4 — both entries open the SAME weekly review screen
 * (spec §7, Q9=(a), §10 item 11).
 *
 * The Today progress ring and the Settings "Weekly review" row each
 * fire their callback — the NavHost wires both to the one
 * WeeklyReview route, so the test pins the callbacks, not the
 * navigation itself. Today renders with manually-constructed
 * ViewModels (real in-memory Room, no Hilt), copying the
 * HabitsInTodayTest setup.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [36])
class WeeklyReviewEntriesTest {

    @get:Rule
    val composeRule = createComposeRule()

    private lateinit var db: NudgyDatabase
    private lateinit var repository: TaskRepository
    private lateinit var tasksViewModel: TasksViewModel
    private lateinit var todayViewModel: TodayViewModel
    // Owns the ViewModels so tearDown can cancel their scopes before
    // the DB closes (same leak as DarkThemeTest, 2026-11-21).
    private val viewModelStore = ViewModelStore()

    @Before
    fun setUp() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        db = Room.inMemoryDatabaseBuilder(context, NudgyDatabase::class.java)
            .allowMainThreadQueries()
            .build()
        repository = TaskRepository(context, db)
        tasksViewModel = TasksViewModel(
            repository = repository,
            createTaskUseCase = CreateTaskUseCase(repository),
            toggleCompletion = ToggleTaskCompletionUseCase(repository),
            updateTask = UpdateTaskUseCase(repository),
            deleteTask = DeleteTaskUseCase(repository),
            addSubtask = AddSubtaskUseCase(repository),
            saveView = SaveViewUseCase(repository)
        )
        todayViewModel = TodayViewModel(
            repository = repository,
            calendarRepository = CalendarRepository(context, db),
            toggleCompletion = ToggleTaskCompletionUseCase(repository),
            carryOverUseCase = CarryOverUseCase(),
            timelineUseCase = GetTodayTimelineUseCase(),
            weeklyReviewUseCase = WeeklyReviewUseCase()
        )
        viewModelStore.put("tasks", tasksViewModel)
        viewModelStore.put("today", todayViewModel)
    }

    @After
    fun tearDown() {
        // Order matters: cancel the ViewModel scopes FIRST so no
        // viewModelScope coroutine can run Room work against the
        // DB once it is closed (same leak as DarkThemeTest).
        viewModelStore.clear()
        // S4-1 round 7 — drain in-flight Room IO before closing the DB.
        Thread.sleep(500)
        db.close()
    }

    @Test
    fun `tapping the Today progress ring fires the weekly review callback`() {
        var reviewClicked = false
        composeRule.setContent {
            TodayScreen(
                onPlanClick = {},
                onAllTasksClick = {},
                onWeeklyReviewClick = { reviewClicked = true },
                tasksViewModel = tasksViewModel,
                todayViewModel = todayViewModel
            )
        }
        composeRule.waitUntil(timeoutMillis = 10_000) {
            composeRule.onAllNodesWithText("Add task")
                .fetchSemanticsNodes().isNotEmpty()
        }

        composeRule.onNodeWithTag("progress_ring").performClick()

        assertTrue(reviewClicked)
    }

    @Test
    fun `the Settings weekly review row fires its callback`() {
        var reviewClicked = false
        composeRule.setContent {
            SettingsShell(onWeeklyReviewClick = { reviewClicked = true })
        }

        // Sprint 6-0 — the Settings screen scrolls (eleven sections
        // + the Weekly review row); the row sits below the fold, so
        // scroll it into view before clicking — the click itself is
        // what this test proves.
        composeRule.onNodeWithTag("settings_weekly_review").performScrollTo().performClick()

        assertTrue(reviewClicked)
    }
}
